#!/usr/bin/env node

import fs from "node:fs/promises";
import path from "node:path";

const ROOT_DIR = process.cwd();
const DATABASE_TYPES_PATH = path.join(ROOT_DIR, "src/types/database.types.ts");
const GENERATED_TYPES_PATH = path.join(ROOT_DIR, "src/types/db.generated.ts");

function getBalancedBlock(source, marker) {
  const markerIndex = source.indexOf(marker);
  if (markerIndex === -1) {
    throw new Error(`Marker non trovato: ${marker}`);
  }

  const blockStart = source.indexOf("{", markerIndex);
  if (blockStart === -1) {
    throw new Error(`Blocco non valido per marker: ${marker}`);
  }

  let depth = 0;
  for (let i = blockStart; i < source.length; i += 1) {
    const char = source[i];
    if (char === "{") depth += 1;
    if (char === "}") {
      depth -= 1;
      if (depth === 0) {
        return source.slice(blockStart + 1, i);
      }
    }
  }

  throw new Error(`Blocco non bilanciato per marker: ${marker}`);
}

function toPascalCase(value) {
  if (!value) return value;
  return value
    .replace(/[_\-\s]+([a-zA-Z0-9])/g, (_, chr) => chr.toUpperCase())
    .replace(/^[a-z]/, (chr) => chr.toUpperCase());
}

function buildGeneratedSource(tableNames) {
  const header = [
    "/* eslint-disable */",
    "// AUTO-GENERATED FILE. DO NOT EDIT.",
    "// Generated by: scripts/generate-db-exports.mjs",
    "",
    "import type { Tables, TablesInsert, TablesUpdate } from '@/types/database.types'",
    "",
    `export const DB_TABLES = ${JSON.stringify(tableNames)} as const`,
    "export type DbTableName = (typeof DB_TABLES)[number]",
    "",
    "export type DbRow<T extends DbTableName> = Tables<T>",
    "export type DbInsert<T extends DbTableName> = TablesInsert<T>",
    "export type DbUpdate<T extends DbTableName> = TablesUpdate<T>",
    "export type DbFullItem<T extends DbTableName> = DbRow<T>",
    "export type DbDto<T extends DbTableName> = DbRow<T>",
    "",
    "export const toDbFullItem = <T extends DbTableName>(row: DbRow<T>): DbFullItem<T> => row",
    "export const toDbDto = <T extends DbTableName>(row: DbRow<T>): DbDto<T> => row",
    "",
  ];

  const perTable = tableNames.flatMap((tableName) => {
    const pascalName = toPascalCase(tableName);

    return [
      `// ${tableName}`,
      `export type ${pascalName}Row = Tables<'${tableName}'>`,
      `export type ${pascalName}Insert = TablesInsert<'${tableName}'>`,
      `export type ${pascalName}Update = TablesUpdate<'${tableName}'>`,
      `export type ${pascalName} = ${pascalName}Row`,
      `export type ${pascalName}Dto = ${pascalName}Row`,
      `export const to${pascalName} = (row: ${pascalName}Row): ${pascalName} => row`,
      `export const to${pascalName}Dto = (row: ${pascalName}Row): ${pascalName}Dto => row`,
      "",
    ];
  });

  return [...header, ...perTable].join("\n");
}

const databaseTypesSource = await fs.readFile(DATABASE_TYPES_PATH, "utf8");
const tablesBlock = getBalancedBlock(databaseTypesSource, "Tables: {");

const tableNames = [];
for (const line of tablesBlock.split("\n")) {
  const match = line.match(/^\s{6}([A-Za-z_][A-Za-z0-9_]*)\s*:\s*{\s*$/);
  if (match) {
    tableNames.push(match[1]);
  }
}

if (tableNames.length === 0) {
  throw new Error("Nessuna tabella trovata in database.types.ts");
}

const generatedSource = buildGeneratedSource(tableNames);
await fs.writeFile(GENERATED_TYPES_PATH, `${generatedSource}\n`, "utf8");

console.log(
  `Generato ${path.relative(ROOT_DIR, GENERATED_TYPES_PATH)} con ${tableNames.length} tabelle`
);
